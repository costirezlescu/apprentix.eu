"""Scroll-driven story pages, from data/published/stories/stories.json (pipeline/stories.py).

  pages/stories/index.html       list of stories
  pages/stories/<id>.html        one story: text steps beside a sticky chart (assets/js/story.js)

The text of every step is in the HTML, so the story reads in full without JavaScript; the chart is
added by the script. Deterministic, rewritten only when content changes.

Run on its own with:  python -m pipeline.render_stories
"""

from __future__ import annotations

import json

from .common import DATA, PUBLISHED, ROOT, read_json
from .render_pages import SITE, breadcrumb, e, page, website, write_text

SRC = PUBLISHED / "stories" / "stories.json"
OUT = ROOT / "pages" / "stories"


def src_link(s: dict) -> str:
    url = s["url"]
    if url.startswith("pages/"):
        return f'<a href="../../{e(url)}">{e(s["label"])}</a>'
    return f'<a href="{e(url)}" target="_blank" rel="noopener">{e(s["label"])}</a>'


def story_page(s: dict, stories: list[dict], updated: str) -> str:
    page_url = f"{SITE}pages/stories/{s['id']}.html"
    # Step text is generated by pipeline/stories.py from numbers and fixed wording, with <strong> only.
    steps = "".join(f'<div class="st-step" data-step="{i}"><p>{st["text"]}</p></div>' for i, st in enumerate(s["steps"]))
    data = json.dumps({"chart": s["chart"], "steps": [st["chart"] for st in s["steps"]]},
                      ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    others = "".join(f'<li><a href="{o["id"]}.html">{e(o["title"])}</a></li>' for o in stories if o["id"] != s["id"])
    body = f"""<nav class="cp-crumbs" aria-label="Breadcrumb"><a href="../../">Apprentix</a> <span aria-hidden="true">›</span> <a href="./">Stories</a> <span aria-hidden="true">›</span> <span aria-current="page">{e(s["title"])}</span></nav>
<article class="st" id="story">
  <header class="st-head">
    <div class="mono cp-group">Story · {e(s["kicker"])}</div>
    <h1>{e(s["title"])}</h1>
    <p class="lede">{e(s["dek"])}</p>
    <p class="st-hint" aria-hidden="true">Scroll to read ↓</p>
  </header>
  <div class="st-scrolly">
    <figure class="st-fig" aria-hidden="true">
      <div class="st-chart" id="st-chart"></div>
      <figcaption class="st-cap" id="st-cap"></figcaption>
    </figure>
    <div class="st-steps">{steps}</div>
  </div>
  <footer class="st-foot">
    <h2>Sources and method</h2>
    <p>{e(s["method"])}</p>
    <ul>{"".join(f"<li>{src_link(x)}</li>" for x in s["sources"])}</ul>
    <p class="provenance">Every number in this story is recomputed from the published data when the sources update: <a href="https://github.com/costirezlescu/apprentix.eu/blob/main/pipeline/stories.py">pipeline/stories.py</a>.</p>
  </footer>
</article>
{f'<section class="cp-sec" aria-labelledby="h-more-stories"><h2 id="h-more-stories">More stories</h2><ul class="cp-more">{others}</ul></section>' if others else ''}
<script type="application/json" id="st-data">{data}</script>
<script type="module" src="../../assets/js/story.js"></script>"""
    ld = {"@context": "https://schema.org", "@graph": [
        {"@type": "Article", "@id": page_url + "#article", "headline": s["title"], "description": s["dek"], "url": page_url,
         "dateModified": updated, "publisher": {"@type": "Organization", "name": "Apprentix", "url": SITE}},
        website(), breadcrumb([("Apprentix", SITE), ("Stories", SITE + "pages/stories/"), (s["title"], page_url)], page_url)]}
    return page(title=f"{s['title']} — Apprentix", description=s["dek"], canonical=page_url, root="../../", body=body,
                json_ld_obj=ld, current="insights", updated=updated, og_type="article")


def index_page(stories: list[dict], updated: str) -> str:
    page_url = f"{SITE}pages/stories/"
    cards = "".join(f"""<li><a class="oc-card" href="{s["id"]}.html">
  <span class="mono cp-group">{e(s["kicker"])}</span>
  <span class="oc-card-q">{e(s["title"])}</span>
  <span class="oc-card-meta">{e(s["dek"])}</span>
</a></li>""" for s in stories)
    body = f"""<nav class="cp-crumbs" aria-label="Breadcrumb"><a href="../../">Apprentix</a> <span aria-hidden="true">›</span> <span aria-current="page">Stories</span></nav>
<header class="in-head">
  <div class="mono">Stories</div>
  <h1>Stories</h1>
  <p class="lede">Findings from the data, told step by step: scroll, and the chart changes with the story. For shorter findings, see the <a href="../insights.html">insights</a>.</p>
</header>
<ul class="oc-cards st-cards">{cards}</ul>"""
    ld = {"@context": "https://schema.org", "@graph": [
        {"@type": "CollectionPage", "@id": page_url, "url": page_url, "name": "Stories", "dateModified": updated},
        website(), breadcrumb([("Apprentix", SITE), ("Stories", page_url)], page_url)]}
    return page(title="Stories about apprenticeships in Europe — Apprentix",
                description="Scroll-driven stories from European apprenticeship data: the French apprenticeship boom, the two families of apprenticeship.",
                canonical=page_url, root="../../", body=body, json_ld_obj=ld, current="insights", updated=updated)


def render_all() -> tuple[list, list[tuple[str, str]]]:
    if not SRC.exists():
        return [], []
    stories = read_json(SRC)["stories"]
    updated = read_json(DATA / "datasets.json")["site"].get("updated", "")
    written, urls, expected = [], [(f"{SITE}pages/stories/", updated)], {"index.html"}
    for s in stories:
        path = OUT / f"{s['id']}.html"
        expected.add(path.name)
        if write_text(path, story_page(s, stories, updated)):
            written.append(path)
        urls.append((f"{SITE}pages/stories/{s['id']}.html", updated))
    if write_text(OUT / "index.html", index_page(stories, updated)):
        written.append(OUT / "index.html")
    for p in OUT.glob("*.html"):
        if p.name not in expected:
            p.unlink()
            written.append(p)
    return written, urls


if __name__ == "__main__":
    w, _ = render_all()
    print(f"Rendered stories: {len(w)} file(s) changed")
