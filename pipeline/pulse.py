"""Policy pulse: what moved in Europe's apprenticeship policies in the latest year of Cedefop's
Timeline of VET policies → data/published/pulse/pulse.json (shown on the home page).

  python -m pipeline.pulse

From the apprenticeship-related policies (concerns_apprenticeship = Yes): those first reported
in the latest year ("new"), and those whose stage changed between the last two reported years
("completed", "discontinued", or "moved" to another stage). Each list keeps at most two
policies per country so one country cannot fill it. Deterministic: no clock.
"""

from __future__ import annotations

import re
from urllib.parse import quote

from .common import PUBLISHED, read_json, write_json

OUT = PUBLISHED / "pulse" / "pulse.json"
DATASET = "vet-policy-timeline"
LIMITS = {"new": 8, "completed": 6, "moved": 6, "discontinued": 4}


def progress(p: dict) -> list[tuple[str, str]]:
    return [(m.group(1), m.group(2).strip()) for m in re.finditer(r"(\d{4}): ([^→]+)", p.get("progress") or "")]


def item(p: dict, kind: str, before: str | None = None, after: str | None = None) -> dict:
    out = {"kind": kind, "title": p.get("title"), "country": p.get("country"), "country_code": p.get("country_code"),
           "flag": p.get("flag", ""), "type": p.get("type"),
           "link": f"pages/explore.html?dataset={DATASET}&open={quote(p['id'])}"}
    if before:
        out["from"], out["to"] = before, after
    return out


def pick(items: list[dict], limit: int) -> list[dict]:
    seen: dict[str, int] = {}
    out = []
    for it in items:
        c = it.get("country_code") or ""
        if seen.get(c, 0) >= 2:
            continue
        seen[c] = seen.get(c, 0) + 1
        out.append(it)
        if len(out) == limit:
            break
    return out


def build() -> dict | None:
    path = PUBLISHED / DATASET / "records.json"
    if not path.exists():
        return None
    app = [p for p in read_json(path) if p.get("concerns_apprenticeship") == "Yes"]
    if not app:
        return None
    year = max(p.get("latest_year") or "" for p in app)
    groups: dict[str, list[dict]] = {k: [] for k in LIMITS}
    ongoing = 0                    # still being implemented, with no change this year
    for p in sorted(app, key=lambda p: (p.get("country") or "", p.get("title") or "")):
        pr = progress(p)
        if p.get("first_year") == year:
            groups["new"].append(item(p, "new"))
        elif len(pr) >= 2 and pr[-1][0] == year and pr[-1][1] != pr[-2][1]:
            before, after = pr[-2][1], pr[-1][1]
            kind = "completed" if after == "Completed" else "discontinued" if after == "Discontinued" else "moved"
            groups[kind].append(item(p, kind, before, after))
        elif p.get("latest_year") == year and p.get("latest_stage") == "Implementation phase":
            ongoing += 1
    meta = read_json(PUBLISHED / DATASET / "meta.json").get("source", {})
    doc = {
        "description": "Apprenticeship policies that started or changed stage in the latest year of Cedefop's Timeline "
                       "of VET policies. Generated by pipeline/pulse.py.",
        "year": year,
        "counts": {k: len(v) for k, v in groups.items()} | {"ongoing": ongoing, "apprenticeship_policies": len(app)},
        "items": {k: pick(v, LIMITS[k]) for k, v in groups.items()},
        "all_link": f"pages/explore.html?dataset={DATASET}&f.concerns_apprenticeship=Yes&f.latest_year={year}",
        "source": {"name": meta.get("name"), "url": meta.get("url")},
    }
    write_json(OUT, doc)
    c = doc["counts"]
    print(f"Pulse: {year}: {c['new']} new, {c['completed']} completed, {c['moved']} moved, {c['discontinued']} discontinued")
    return doc


if __name__ == "__main__":
    build()
