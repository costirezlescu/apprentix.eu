def default_obs(ind: dict) -> dict[tuple[str, str], dict]:
    """(geo, time) -> observation at the default breakdown (same rule as the country pages)."""
    dims = ind.get("dims") or []
    best = {}
    for o in ind.get("series", []):
        if all((o.get("dims") or {}).get(d["key"], d.get("default")) == d.get("default") for d in dims):
            best[(o["geo"], o["time"])] = o
    return best


def indicator_chunks(index: list[dict], names: dict[str, str], fmt_value) -> list[dict]:
    out = []
    for meta in sorted(index, key=lambda m: m["id"]):
        ind = read_json(INDICATORS / f"{meta['id']}.json")
        p = ind.get("provenance") or {}
        unit = ind.get("unit")
        obs = default_obs(ind)
        latest: dict[str, dict] = {}
        for (g, t), o in obs.items():
            if g not in latest or t > latest[g]["time"]:
                latest[g] = o
        dims_txt = "; ".join(
            f"{d.get('label', d['key'])} (key '{d['key']}', default '{d.get('default')}' = {d['values'].get(d.get('default'), '')}; "
            f"{len(d['values'])} values)" for d in ind.get("dims") or [])
        lines = [
            f"Indicator: {ind['title']} (id {ind['id']})",
            f"Topic: {ind.get('topic', '')}. Unit: {unit or 'n/a'}.",
            f"Definition: {clip(ind.get('description'), 900)}",
        ]
        if ind.get("comparability"):
            lines.append(f"Comparability: {clip(ind['comparability'], 900)}")
        if ind.get("national"):
            lines.append("National statistic: definitions are the country's own and NOT comparable with other countries.")
        if ind.get("target"):
            lines.append(f"Target: {ind['target'].get('label', '')}")
        if dims_txt:
            lines.append(f"Breakdowns: {dims_txt}. Values below are for the default breakdown.")
        lines.append(f"Publisher: {p.get('publisher', '')} ({p.get('dataset_code', '')}); licence {p.get('licence', 'see source')}; source {p.get('source_url', '')}")
        cov = ind.get("coverage") or {}
        if cov.get("time"):
            lines.append(f"Years covered: {cov['time'][0]}–{cov['time'][-1]}.")
        geos = sorted(latest, key=lambda g: (g != "EU27", g))
        single = len([g for g in geos if g != "EU27"]) <= 1
        if single:
            # One country: give the whole default series (e.g. a national count over time).
            series = sorted(obs.values(), key=lambda o: (o["geo"], o["time"]))
            if series and len(series[0]["time"]) > 4:
                # Monthly/quarterly: the last period of each year, then the last 6 periods.
                last_of_year = {}
                for o in series:
                    last_of_year[o["time"][:4]] = o
                tail = series[-6:]
                series = [o for o in last_of_year.values() if o not in tail] + tail
            vals = ", ".join(f"{o['time']}: {fmt_value(o['value'], unit)}{' (' + o['flag'] + ')' if o.get('flag') else ''}" for o in series[-40:])
            if geos:
                lines.append(f"Series for {names.get(geos[0], geos[0])}: {vals}")
        else:
            vals = "; ".join(
                f"{g} {latest[g]['time']}: {fmt_value(latest[g]['value'], unit)}{' (' + latest[g]['flag'] + ')' if latest[g].get('flag') else ''}"
                for g in geos)
            lines.append(f"Latest value per country: {vals}")
            eu = sorted((t, o) for (g, t), o in obs.items() if g == "EU27")
            if len(eu) > 1:
                lines.append("EU-27 trend: " + ", ".join(f"{t}: {fmt_value(o['value'], unit)}" for t, o in eu[-8:]))
        if ind.get("flags"):
            lines.append("Flags: " + "; ".join(f"{k} = {v}" for k, v in sorted(ind["flags"].items())))
        cc = geos[0] if single and geos and geos[0] != "EU27" else None
        out.append(chunk(f"indicator:{ind['id']}", indicator_url(ind["id"]), ind["title"], "indicator", "\n".join(lines), cc))
    return out


def dataset_chunks(manifest: dict) -> list[dict]:
    out = []
    for d in manifest["datasets"]:
        meta = read_json(ROOT / d["path"] / "meta.json")
        records = read_json(ROOT / d["path"] / "records.json")
        src = meta.get("source", {})
        fields = []
        for f in meta["fields"]:
            if f.get("type") == "hidden" and f["key"] not in ("country_code",):
                continue
            desc = f"{f['key']} ({f.get('label', '')}, {f.get('type', '')})"
            if f.get("type") == "category":
                cnt = Counter(x for r in records for x in (r.get(f["key"]) if isinstance(r.get(f["key"]), list) else [r.get(f["key"])]) if x not in (None, ""))
                if f["key"] not in ("country",) and len(cnt) <= 40:
                    top = [v for v, _ in sorted(cnt.items(), key=lambda kv: (-kv[1], str(kv[0])))[:12]]
                    desc += " values: " + " | ".join(str(v) for v in top)
                else:
                    desc += f" ({len(cnt)} distinct values)"
            fields.append(desc)
        text = "\n".join([
            f"Dataset: {d['title']} (id {d['id']}), {len(records):,} records. {d.get('tagline', '')}",
            f"Coverage: {d.get('coverage', '')}",
            f"Description: {clip(meta.get('description'), 1200)}",
            f"Source: {src.get('name', '')} {src.get('url', '')}. Licence: {clip(src.get('licence'), 300)}",
            f"Caveat: {clip(src.get('caveat'), 900)}",
            f"Explore: {explore(d['id'])}",
            "Fields (use with query_records): " + "; ".join(fields),
        ])
        out.append(chunk(f"dataset:{d['id']}", dataset_url(d["id"]), d["title"], "dataset", text))
    return out


def scheme_chunks(meta: dict, records: list[dict]) -> list[dict]:
    out = []
    for r in sorted(records, key=lambda r: r["id"]):
        cc = r.get("country_code")
        text = f"Apprenticeship scheme in {r.get('country')}: {r.get('name_en')} ({r.get('name_original', '')}).\n" + record_text(meta, r, long=1200)
        out.append(chunk(f"scheme:{r['id']}", f"{country_url(cc)}#scheme-{r['id']}" if cc else explore("apprenticeship-schemes", r["id"]),
                         f"{r.get('name_en')} — {r.get('country')}", "scheme", text, cc))
    return out


def simple_record_chunks(did: str, kind: str, meta: dict, records: list[dict], title_key: str, long: int = LONG) -> list[dict]:
    out = []
    for r in sorted(records, key=lambda r: r["id"]):
        title = f"{r.get(title_key)} — {r.get('country')}" if r.get("country") and r.get("country") != r.get(title_key) else str(r.get(title_key))
        text = f"{meta.get('title', did)} record.\n" + record_text(meta, r, long=long)
        out.append(chunk(f"{kind}:{r['id']}", explore(did, r["id"]), title, kind, text, r.get("country_code")))
    return out


