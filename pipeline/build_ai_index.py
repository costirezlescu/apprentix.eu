"""Retrieval index for "Ask Apprentix" (the AI assistant, see worker/).

  data/ai/search-index.json                      compact text chunks the Worker searches (BM25)
  data/ai/records/vet-qualifications/<cc>.json   slim per-country shards of the Europass
                                                 qualifications (the full records.json is too
                                                 large to load inside a Cloudflare Worker)

Each chunk is {id, url, title, kind, country_code?, text}: plain text written from the
published data, with absolute https://apprentix.eu/… URLs the assistant cites. Nothing
here is generated by a model; it is a re-statement of data/published/.

Deterministic: no clock, sorted inputs, files rewritten only when their content changes.
Called at the end of pipeline/build.py all(); run on its own with
    python -m pipeline.build_ai_index
"""

