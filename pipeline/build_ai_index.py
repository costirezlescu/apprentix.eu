def nqf_chunks(records: list[dict], names: dict[str, str]) -> list[dict]:
    by: dict[str, list] = {}
    for r in records:
        by.setdefault(r.get("country") or "", []).append(r)
    out = []
    for country in sorted(by):
        rs = by[country]
        cc = rs[0].get("country_code")
        lines = [f"Qualification levels in the national qualifications framework of {country} (Cedefop NQF online tool, state of play {rs[0].get('reference_year', '2024')}). Each line: qualification type — national level — EQF level{' — apprenticeship/craft' }."]
        for r in sorted(rs, key=lambda r: r["id"]):
            lines.append(f"- {r.get('qualification_type')} — NQF {r.get('nqf_level', '')} — {fmt(r.get('eqf_level')) or 'EQF not stated'}{' — APPRENTICESHIP/CRAFT' if r.get('apprenticeship_or_craft') == 'Yes' else ''}")
        lines.append(f"Source: {rs[0].get('source_url', '')}")
        slug = "-".join("".join(ch if ch.isalnum() else " " for ch in country.lower()).split())
        out.append(chunk(f"nqf:{slug}", explore("nqf-qualification-levels", country=country),
                         f"NQF qualification levels — {country}", "nqf", "\n".join(lines), cc))
    return out


def country_chunks(D, facts: dict, fmt_value, key_figures, names) -> list[dict]:
    out = []
    for c in D["countries"]:
        code = c["code"]
        f = facts.get(code)
        if not f:
            continue
        name = c["name"]
        url = country_url(code)
        lines = [f"Country profile: {name} ({code}). Apprentix page: {url}"]
        if f["schemes"]:
            lines.append(f"Apprenticeship schemes ({len(f['schemes'])}, Cedefop database on apprenticeship schemes):")
            for s in f["schemes"]:
                lines.append(
                    f"- {s.get('name_en')} ({s.get('name_original', '')}): level {fmt(s.get('education_level_detail') or s.get('education_level'))}; "
                    f"duration {fmt(s.get('duration'))}; workplace {fmt(s.get('workplace_time'))} ({fmt(s.get('workplace_time_detail'))}); "
                    f"pay {fmt(s.get('compensation'))}; Cedefop coded pay {fmt(s.get('q_compensation'))}; minimum workplace share {fmt(s.get('q_min_workplace_share'))}; "
                    f"learner status {fmt(s.get('q_learner_status'))}; contract {fmt(s.get('q_contract_type'))}; apprentices {fmt(s.get('learners'))}; "
                    f"qualification {fmt(s.get('qualification'))}; access to higher education {fmt(s.get('q_access_to_he'))}; share of VET learners {fmt(s.get('q_share_of_vet'))}.")
        rows, national = key_figures(D, code)
        if rows:
            lines.append("Key figures (latest; EU-27 same year where published):")
            for r in rows:
                ind, o, eu = r["ind"], r["obs"], r["eu"]
                lines.append(f"- {ind['title']} [{ind['id']}]: {fmt_value(o['value'], ind.get('unit'))} ({o['time']}{', flag ' + o['flag'] if o.get('flag') else ''})"
                             + (f"; EU-27 {fmt_value(eu['value'], ind.get('unit'))}" if eu else "")
                             + f" — {(ind.get('provenance') or {}).get('publisher', '')}")
        if national:
            lines.append("National statistics (own definitions; not comparable across countries):")
            for r in national:
                ind, o = r["ind"], r["obs"]
                lines.append(f"- {ind['title']} [{ind['id']}]: {fmt_value(o['value'], ind.get('unit'))} ({o['time']}) — {(ind.get('provenance') or {}).get('publisher', '')}")
        if f["policies"]:
            recent = sorted(f["app_policies"], key=lambda p: (p.get("latest_year") or "", p.get("first_year") or "", p["id"]), reverse=True)[:8]
            lines.append(f"VET policies since 2015 (Cedefop/ReferNet timeline): {len(f['policies'])}, of which {len(f['app_policies'])} concern apprenticeship. Most recent apprenticeship policies: "
                         + "; ".join(f"{p.get('title')} ({fmt(p.get('type'))}, {fmt(p.get('latest_stage'))} {fmt(p.get('latest_year'))})" for p in recent))
        fi = f["financing_instruments"]
        if fi:
            lines.append(f"Financing instruments for apprenticeships (Cedefop, 2016–17 reference period): " + "; ".join(f"{r['title']} ({fmt(r.get('type'))})" for r in fi))
        nq = f["nqf_qualification_levels"]
        app_q = [q for q in nq if q.get("apprenticeship_or_craft") == "Yes"]
        if nq:
            lines.append(f"National qualifications framework: {len(nq)} qualification types; apprenticeship/craft ones: "
                         + ("; ".join(f"{q['qualification_type']} (NQF {q.get('nqf_level', '')}, {fmt(q.get('eqf_level')) or 'EQF not stated'})" for q in app_q) or "none named"))
        if f["vet_systems"]:
            v = f["vet_systems"][0]
            lines.append(f"VET system description: Cedefop VET in Europe ({v.get('version', '')}), by {v.get('refernet_partner', '')}: {v.get('source_url', '')}")
        if f["recognition_vet_qualifications"]:
            lines.append("Recognition of foreign VET qualifications: mapped by Cedefop (2026) for " + ", ".join(r.get("system") or r["country"] for r in f["recognition_vet_qualifications"]) + ".")
        if f["erasmus_vet_organisations"]:
            lines.append(f"Erasmus+ accredited VET organisations: {len(f['erasmus_vet_organisations']):,}.")
        if f["cove_projects"]:
            coord = [r for r in f["cove_projects"] if r.get("coordinator_country_code") == code]
            lines.append(f"Centres of Vocational Excellence: takes part in {len(f['cove_projects'])} projects, coordinating {len(coord)}.")
        if f["catalogue"]:
            capp = sum(1 for r in f["catalogue"] if r.get("concerns_apprenticeship") == "Yes")
            lines.append(f"Open datasets on data.europa.eu: {len(f['catalogue'])} ({capp} on apprenticeship).")
        lines.append(f"Indicators with data for {name}: {len(f['indicators'])}.")
        out.append(chunk(f"country:{code}", url, f"{name} — apprenticeships and VET", "country", "\n".join(lines), code))
    return out


def insight_chunks() -> list[dict]:
    if not INSIGHTS.exists():
        return []
    try:
        data = read_json(INSIGHTS)
    except Exception:
        return []
    items = data if isinstance(data, list) else (data.get("insights") or data.get("items") or [])
    out = []
    for it in items:
        if not isinstance(it, dict) or not it.get("id"):
            continue
        cav = it.get("caveats") or it.get("caveat") or ""
        lines = [f"Insight: {it.get('title', '')}", f"Finding: {fmt(it.get('finding'))}"]
        if it.get("detail"):
            lines.append(f"Detail: {clip(fmt(it.get('detail')), 600)}")
        if cav:
            lines.append(f"Caveats: {clip(fmt(cav), 600)}")
        cc = it.get("country_code") if isinstance(it.get("country_code"), str) else None
        out.append(chunk(f"insight:{it['id']}", f"{SITE}pages/insights.html#{quote(str(it['id']))}", str(it.get("title", it["id"])),
                         "insight", "\n".join(lines), cc))
    return sorted(out, key=lambda c: c["id"])


