def build() -> dict:
    from .render_pages import country_facts, fmt_value, has_content, key_figures, load

    D = load()
    names = {c["code"]: c["name"] for c in D["ref"]["countries"]}
    names["EU27"] = "EU-27"
    facts = {}
    for c in D["countries"]:
        f = country_facts(D, c["code"])
        if has_content(f):
            facts[c["code"]] = f

    def ds(did):
        p = PUBLISHED / did
        if not (p / "records.json").exists():
            return None, []
        return read_json(p / "meta.json"), read_json(p / "records.json")

    chunks: list[dict] = []
    chunks += guide_chunks()
    chunks += country_chunks(D, facts, fmt_value, key_figures, names)
    chunks += indicator_chunks(D["index"], names, fmt_value)
    chunks += dataset_chunks(D["manifest"])
    m, r = ds("apprenticeship-schemes")
    if m:
        chunks += scheme_chunks(m, r)
    m, r = ds("financing-instruments")
    if m:
        chunks += simple_record_chunks("financing-instruments", "financing", m, r, "title", long=500)
    m, r = ds("recognition-vet-qualifications")
    if m:
        chunks += simple_record_chunks("recognition-vet-qualifications", "recognition", m, r, "system", long=600)
    m, r = ds("vet-systems")
    if m:
        chunks += simple_record_chunks("vet-systems", "vet-system", m, r, "title", long=400)
    m, r = ds("vet-policy-timeline")
    if m:
        chunks += policy_chunks(m, r)
    m, r = ds("cove-projects")
    if m:
        chunks += cove_chunks(m, r)
    m, r = ds("nqf-qualification-levels")
    if m:
        chunks += nqf_chunks(r, names)
    m, r = ds("erasmus-vet-organisations")
    if m:
        chunks += erasmus_summaries(r, names)
    m, r = ds("data-catalogue")
    if m:
        chunks += catalogue_summaries(r, names)
    m, r = ds("vet-qualifications")
    shards = []
    if m:
        chunks += qualification_summaries(r, names)
        shards = qualification_shards(r)
    chunks += insight_chunks()

    ids = [c["id"] for c in chunks]
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        raise ValueError(f"duplicate AI index chunk ids: {sorted(dupes)[:5]}")

    body = {
        "description": "Search index for Ask Apprentix (worker/). Text chunks restating data/published/; generated by pipeline/build_ai_index.py — do not edit.",
        "updated": D["updated"],
        "count": len(chunks),
        "shards": {"vet-qualifications": sorted(p.stem for p in (SHARDS / "vet-qualifications").glob("*.json"))},
    }
    head = json.dumps(body, ensure_ascii=False, separators=(",", ":"))[:-1]
    text = head + ',"chunks":[\n' + ",\n".join(json.dumps(c, ensure_ascii=False, separators=(",", ":")) for c in chunks) + "\n]}\n"
    size = len(text.encode("utf-8"))
    if size > MAX_INDEX_BYTES:
        print(f"warning: AI search index is {size / 1e6:.1f} MB (limit {MAX_INDEX_BYTES / 1e6:.0f} MB)")
    changed = write_if_changed(INDEX, text)
    kinds = Counter(c["kind"] for c in chunks)
    print(f"AI index: {len(chunks)} chunks, {size / 1e6:.2f} MB ({', '.join(f'{k} {n}' for k, n in sorted(kinds.items()))})"
          f"{'' if changed else ' (unchanged)'}; {len(shards)} shard file(s) changed")
    return {"chunks": len(chunks), "bytes": size, "kinds": dict(kinds)}


if __name__ == "__main__":
    build()
