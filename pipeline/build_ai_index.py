# Slim rows: the Worker rebuilds europass_url from the id ("qdr-<uuid>"), and treats a missing
# "apprenticeship" as "Not stated". Learning-outcome summaries are left out (size).
SHARD_FIELDS = ["id", "title", "title_original", "eqf_level", "nqf_level", "apprenticeship", "field",
                "awarding_body", "duration", "credits", "volume"]


def qualification_shards(records: list[dict]) -> list[Path]:
    by: dict[str, list] = {}
    for r in records:
        if r.get("country_code"):
            by.setdefault(r["country_code"], []).append(r)
    folder = SHARDS / "vet-qualifications"
    written, expected = [], set()
    for cc in sorted(by):
        rows = []
        for r in sorted(by[cc], key=lambda r: r["id"]):
            row = {k: r[k] for k in SHARD_FIELDS if r.get(k) not in (None, "", [], "Not stated")}
            if row.get("title_original") == row.get("title"):
                row.pop("title_original")
            rows.append(row)
        path = folder / f"{cc}.json"
        expected.add(path.name)
        text = "[\n" + ",\n".join(json.dumps(x, ensure_ascii=False, separators=(",", ":")) for x in rows) + "\n]\n"
        if write_if_changed(path, text):
            written.append(path)
    if folder.exists():
        for p in folder.glob("*.json"):
            if p.name not in expected:
                p.unlink()
                written.append(p)
    return written


