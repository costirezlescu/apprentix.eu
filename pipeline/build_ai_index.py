# ---------------------------------------------------------------- helpers --

def clip(s, n: int = LONG) -> str:
    s = " ".join(str(s or "").split())
    return s if len(s) <= n else s[: n - 1].rstrip() + "…"


def fmt(v) -> str:
    if v is None or v == "" or v == []:
        return ""
    if isinstance(v, list):
        return "; ".join(str(x) for x in v if x not in (None, ""))
    return str(v)


def explore(dataset: str, open_id: str | None = None, **filters) -> str:
    params = [("dataset", dataset)] + [(f"f.{k}", v) for k, v in filters.items()]
    if open_id:
        params.append(("open", open_id))
    return SITE + "pages/explore.html?" + urlencode(params, quote_via=quote)


def country_url(code: str) -> str:
    return f"{SITE}pages/countries/{code.lower()}.html"


def indicator_url(iid: str) -> str:
    return f"{SITE}pages/indicators/{quote(iid)}.html"


def dataset_url(did: str) -> str:
    return f"{SITE}pages/datasets/{quote(did)}.html"


def chunk(id_: str, url: str, title: str, kind: str, text: str, cc: str | None = None) -> dict:
    c = {"id": id_, "url": url, "title": title, "kind": kind}
    if cc:
        c["country_code"] = cc
    c["text"] = text.strip()
    return c


def record_text(meta: dict, rec: dict, skip: set[str] = frozenset(), long: int = LONG) -> str:
    """'Label: value' lines for every described field of a record, in meta order."""
    lines = []
    for f in meta["fields"]:
        k, t = f["key"], f.get("type")
        if k in skip or t == "hidden" or k == "id":
            continue
        v = fmt(rec.get(k))
        if not v:
            continue
        if t == "longtext":
            v = clip(v, long)
        lines.append(f"{f.get('label', k)}: {v}")
    return "\n".join(lines)


def write_if_changed(path: Path, text: str) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8")
    return True


