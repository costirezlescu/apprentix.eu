def per_country_counts(records: list[dict], key: str) -> str:
    c = Counter(x for r in records for x in (r.get(key) if isinstance(r.get(key), list) else [r.get(key)]) if x not in (None, ""))
    return ", ".join(f"{v} {n:,}" for v, n in sorted(c.items(), key=lambda kv: (-kv[1], str(kv[0]))))


def qualification_summaries(records: list[dict], names: dict[str, str]) -> list[dict]:
    """The Europass qualifications are summarised per country, not indexed one by one."""
    by: dict[str, list] = {}
    for r in records:
        by.setdefault(r.get("country_code") or "", []).append(r)
    out = []
    for cc in sorted(k for k in by if k):
        rs = by[cc]
        app = [r for r in rs if r.get("apprenticeship") == "Apprenticeship / dual"]
        fields = Counter(x for r in rs for x in (r.get("field") or []))
        text = "\n".join([
            f"National VET qualifications in {names.get(cc, cc)} published to Europass (QDR): {len(rs):,} qualifications at EQF levels 2–5.",
            f"By EQF level: {per_country_counts(rs, 'eqf_level')}.",
            f"Apprenticeship / work-based route flag: {per_country_counts(rs, 'apprenticeship')}.",
            f"Largest fields of education: {', '.join(f'{k} {n:,}' for k, n in sorted(fields.items(), key=lambda kv: (-kv[1], kv[0]))[:8])}.",
            "Examples of apprenticeship qualifications: " + "; ".join(sorted({r['title'] for r in app})[:12]) if app else "No qualification is flagged as an apprenticeship route in the register.",
            "Coverage depends on what the national authority has published to Europass; counts are not comparable between countries.",
            f"Search them with query_records(dataset_id='vet-qualifications', filters={{'country_code': '{cc}'}}, text=...).",
        ])
        out.append(chunk(f"vet-qualifications:{cc}", explore("vet-qualifications", country=names.get(cc, cc)) if cc in names else explore("vet-qualifications"),
                         f"VET qualifications in {names.get(cc, cc)} (Europass)", "qualifications-summary", text, cc))
    return out


def catalogue_summaries(records: list[dict], names: dict[str, str]) -> list[dict]:
    by: dict[str, list] = {}
    for r in records:
        by.setdefault(r.get("country_code") or "EU", []).append(r)
    out = []
    for cc in sorted(by):
        rs = by[cc]
        app = sorted((r for r in rs if r.get("concerns_apprenticeship") == "Yes"), key=lambda r: r["id"])
        pubs = Counter(r.get("publisher") for r in rs if r.get("publisher") and r.get("publisher") != "Not stated")
        label = names.get(cc, "EU-level and unassigned publishers")
        text = "\n".join([
            f"Open datasets on apprenticeship and VET from {label} listed on data.europa.eu: {len(rs):,} ({len(app):,} specifically about apprenticeship).",
            f"Main publishers: {', '.join(f'{k} ({n})' for k, n in sorted(pubs.items(), key=lambda kv: (-kv[1], kv[0]))[:6])}.",
            "Apprenticeship datasets include: " + "; ".join(clip(r.get("title"), 120) for r in app[:10]) if app else "",
        ])
        out.append(chunk(f"data-catalogue:{cc}", explore("data-catalogue", country=rs[0].get("country")) if rs[0].get("country") else explore("data-catalogue"),
                         f"Open datasets — {label}", "catalogue-summary", text, cc if cc in names else None))
    return out


