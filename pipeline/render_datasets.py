def feed_xml(D, datasets: list[dict], inds: list[dict]) -> str:
    entries = []
    for ind in inds:
        p = ind.get("provenance") or {}
        ts = p.get("retrieved_at") or ""
        day = iso_date(ts) or (iso_date((p.get("raw_file") or "").split("/")[-1][:10]))
        if not day:
            continue
        stamp = ts if re.match(r"\d{4}-\d{2}-\d{2}T", ts) else day + "T00:00:00Z"
        cov = ind.get("coverage") or {}
        t = cov.get("time") or ["", ""]
        summary = (f"{ind['title']} ({p.get('publisher', '')}): new or revised data retrieved {day}"
                   f"{'; source updated ' + str(p['source_updated']) if p.get('source_updated') else ''}. "
                   f"{cov.get('observations', 0):,} observations, {len(cov.get('geos') or [])} geographies, {t[0]}–{t[1]}.")
        entries.append((stamp, day, f"indicator/{ind['id']}", ind["title"],
                        f"{SITE}pages/indicators/{quote(ind['id'])}.html", summary, ind.get("topic") or "Indicators"))
    for ds in datasets:
        day = dataset_dates(ds, "")
        if not day:
            continue
        did = ds["entry"]["id"]
        title_ = ds["meta"].get("title") or did
        src = ds["meta"].get("source") or {}
        summary = f"{title_}: {len(ds['records']):,} records, read from {src.get('name', 'the source')} on {day}."
        entries.append((day + "T00:00:00Z", day, f"dataset/{did}", title_,
                        f"{SITE}pages/datasets/{quote(did)}.html", summary, "Datasets"))
    entries.sort(key=lambda x: (x[0], x[2]), reverse=True)
    if entries:
        newest = entries[0][1]
        import datetime as dt
        cutoff = (dt.date.fromisoformat(newest) - dt.timedelta(days=FEED_WINDOW)).isoformat()
        entries = [x for x in entries if x[1] >= cutoff][:FEED_MAX]
    updated = entries[0][0] if entries else (D["updated"] + "T00:00:00Z")
    x = xml_escape
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<feed xmlns="http://www.w3.org/2005/Atom" xml:lang="en">',
           '  <title>Apprentix — data updates</title>',
           '  <subtitle>Indicators and datasets on European apprenticeship and VET whose data changed, newest first.</subtitle>',
           f'  <id>{SITE}{FEED_PATH}</id>',
           f'  <link rel="self" type="application/atom+xml" href="{SITE}{FEED_PATH}"/>',
           f'  <link rel="alternate" type="text/html" href="{SITE}pages/data.html"/>',
           f'  <updated>{x(updated)}</updated>',
           f'  <author><name>Apprentix</name><uri>{SITE}</uri></author>',
           '  <rights>Each dataset keeps its original publisher\'s licence; see the linked page.</rights>']
    for stamp, day, key, title_, link, summary, cat in entries:
        out += ['  <entry>',
                f'    <id>tag:apprentix.eu,{day}:{x(key)}</id>',
                f'    <title>Updated: {x(title_)}</title>',
                f'    <link rel="alternate" type="text/html" href="{x(link)}"/>',
                f'    <updated>{x(stamp)}</updated>',
                f'    <category term="{x(cat, {chr(34): "&quot;"})}"/>',
                f'    <summary>{x(summary)}</summary>',
                '  </entry>']
    out.append('</feed>')
    return "\n".join(out) + "\n"


