def replace_between(text: str, start: str, end: str, inner: str) -> str | None:
    i, j = text.find(start), text.find(end)
    if i < 0 or j < i:
        return None
    return text[: i + len(start)] + "\n" + inner + "\n" + text[j:]


def update_data_page(D, datasets, inds, names) -> bool:
    if not DATA_PAGE.exists():
        return False
    text = DATA_PAGE.read_text(encoding="utf-8")
    from .render_pages import json_ld
    new = replace_between(text, CAT_START, CAT_END,
                          f'<script type="application/ld+json">\n{json_ld(catalog_ld(D, datasets, inds, names))}\n</script>')
    if new is None:
        print("  warning: pages/data.html has no catalog JSON-LD markers; skipped")
