# ---------------------------------------------------------------- helpers --

def iso_date(s) -> str | None:
    """YYYY-MM-DD from a date or timestamp string, or YYYY-MM -> YYYY-MM-01; else None."""
    s = str(s or "")
    if re.match(r"\d{4}-\d{2}-\d{2}", s):
        return s[:10]
    if re.fullmatch(r"\d{4}-\d{2}", s):
        return s + "-01"
    return None


def clip(text: str, n: int) -> str:
    text = re.sub(r"\s+", " ", text or "").strip()
    if len(text) <= n:
        return text
    cut = text[: n - 1].rsplit(" ", 1)[0].rstrip(",;:—-")
    return cut + "…"


def ld_description(*parts: str, fallback: str) -> str:
    """Google requires 50–5000 characters."""
    text = " ".join(p.strip() for p in parts if p and p.strip())
    if len(text) < 50:
        text = (text + " " + fallback).strip()
    return clip(text, 5000)


def organization(name: str | None) -> list[dict]:
    """Publisher string -> schema.org Organizations ('X; calculation by Apprentix' -> X + Apprentix)."""
    if not name:
        return [APPRENTIX]
    orgs = []
    base, _, rest = name.partition("; calculation by Apprentix")
    base = base.strip()
    if base:
        o = {"@type": "Organization", "name": base}
        if base in PUBLISHER_URLS:
            o["url"] = PUBLISHER_URLS[base]
        orgs.append(o)
    if _ or not orgs:
        orgs.append(APPRENTIX)
    return orgs


def one_or_list(xs: list):
    return xs[0] if len(xs) == 1 else xs


def licence_ld(lic: str | None, url: str | None):
    url = url or LICENCES.get(lic or "")
    if url:
        return url
    if lic:
        return {"@type": "CreativeWork", "name": clip(lic, 300)}
    return None


def places(codes: list[str], names: dict[str, str]) -> list[dict]:
    return [{"@type": "Place", "name": names.get(c, c)} for c in codes]


def abs_url(path: str) -> str:
    return SITE + quote(path)


def year_range(first: str | None, last: str | None) -> str | None:
    if not first:
        return None
    return first if first == last or not last else f"{first}/{last}"


