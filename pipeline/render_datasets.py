def load_datasets(D) -> list[dict]:
    out = []
    for d in D["manifest"].get("datasets", []):
        base = ROOT / d.get("path", f"data/published/{d['id']}")
        if not (base / "meta.json").exists() or not (base / "records.json").exists():
            continue
        meta = read_json(base / "meta.json")
        records = read_json(base / "records.json")
        if not isinstance(records, list):
            continue
        rel = base.relative_to(ROOT).as_posix()
        out.append({"entry": d, "meta": meta, "records": records, "path": rel})
    return out


def dataset_dates(ds: dict, fallback: str) -> str:
    src = ds["meta"].get("source") or {}
    dates = [x for x in [iso_date(src.get("retrieved"))] if x]
    dates += [x for r in ds["records"] if isinstance(r, dict) for x in [iso_date(r.get("retrieved"))] if x]
    return max(dates) if dates else fallback


def dataset_years(records: list[dict]) -> str | None:
    years = []
    for r in records:
        for k in ("first_year", "latest_year", "year"):
            v = r.get(k) if isinstance(r, dict) else None
            for x in (v if isinstance(v, list) else [v]):
                m = re.match(r"(\d{4})$", str(x or ""))
                if m and 1900 < int(m.group(1)) < 2100:
                    years.append(m.group(1))
    if not years:
        return None
    return year_range(min(years), max(years))


