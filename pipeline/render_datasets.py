def sync_dir(folder: Path, expected: set[str], written: list[Path]) -> None:
    for p in folder.glob("*.html"):
        if p.name not in expected:
            p.unlink()
            written.append(p)


def render_all(D) -> tuple[list[Path], list[tuple[str, str]]]:
    """Write every page; return (changed files, sitemap URLs with lastmod)."""
    names = {c["code"]: c["name"] for c in D["ref"]["countries"]}
    names["EU27"] = "EU-27"
    written: list[Path] = []
    urls: list[tuple[str, str]] = []

    index = sorted(D["index"], key=lambda i: i["id"])
    inds = [read_json(INDICATORS / f"{m['id']}.json") for m in index]
    by_topic: dict[str, list[dict]] = {}
    for m in index:
        key = topic_of(m) + ("|" + m["coverage"]["geos"][0] if m.get("national") and len(m["coverage"]["geos"]) == 1 else "")
        by_topic.setdefault(key, []).append(m)

    expected = {"index.html"}
    for m, ind in zip(index, inds):
        key = topic_of(m) + ("|" + m["coverage"]["geos"][0] if m.get("national") and len(m["coverage"]["geos"]) == 1 else "")
        path = IND_OUT / f"{ind['id']}.html"
        expected.add(path.name)
        if write_text(path, render_indicator(D, ind, names, sorted(by_topic[key], key=lambda s: s["title"]))):
            written.append(path)
        urls.append((f"{SITE}pages/indicators/{quote(ind['id'])}.html",
                     iso_date((ind.get("provenance") or {}).get("retrieved_at")) or D["updated"]))
    if write_text(IND_OUT / "index.html", render_indicator_index(D, index, names)):
        written.append(IND_OUT / "index.html")
    sync_dir(IND_OUT, expected, written)
    urls.insert(0, (SITE + "pages/indicators/", max((u[1] for u in urls), default=D["updated"])))

    datasets = load_datasets(D)
    expected = set()
    for ds in datasets:
        path = DS_OUT / f"{ds['entry']['id']}.html"
        expected.add(path.name)
        if write_text(path, render_dataset(D, ds, names, datasets)):
            written.append(path)
        urls.append((f"{SITE}pages/datasets/{quote(ds['entry']['id'])}.html", dataset_dates(ds, D["updated"])))
    if DS_OUT.exists():
        sync_dir(DS_OUT, expected, written)

    if update_data_page(D, datasets, inds, names):
        written.append(DATA_PAGE)
    if write_text(FEED, feed_xml(D, datasets, inds)):
        written.append(FEED)
    print(f"Rendered: {len(inds)} indicator pages + index, {len(datasets)} dataset pages, catalogue, feed")
    return written, urls
